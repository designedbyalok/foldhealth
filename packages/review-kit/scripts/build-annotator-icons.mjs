// Generates src/annotator-icons.js: the annotator toolbar's icons, Solar
// linear icons (480 Design, CC BY 4.0) redrawn at a 1px stroke to match the
// rest of the kit. Run after changing the map:
//   node scripts/build-annotator-icons.mjs
import { writeFileSync } from 'node:fs';

// Toolbar slot → Solar icon name (without the -linear suffix).
const SOLAR = {
  select: 'cursor',
  rect: 'stop',
  arrow: 'arrow-right-up',
  pen: 'pen',
  text: 'text-square',
  redact: 'eye-closed',
  crop: 'crop',
  undo: 'undo-left',
  redo: 'undo-right',
  remove: 'trash-bin-minimalistic',
  done: 'check-read',
};

// Shapes Solar has no plain glyph for, drawn in the same style.
const STROKE = 'fill="none" stroke="currentColor" stroke-width="1" stroke-linecap="round" stroke-linejoin="round"';
const CUSTOM = {
  highlight: `<rect x="3.5" y="3.5" width="17" height="17" rx="4" fill="currentColor" fill-opacity=".22" stroke="currentColor" stroke-width="1"/>`,
  ellipse: `<circle cx="12" cy="12" r="8.5" ${STROKE}/>`,
  line: `<path d="M5 19 19 5" ${STROKE}/>`,
  step: `<circle cx="12" cy="12" r="8.5" ${STROKE}/><path d="M10.5 9.5 12.5 8v8" ${STROKE}/>`,
};

const names = Object.values(SOLAR).map(n => `${n}-linear`);
const res = await fetch(`https://api.iconify.design/solar.json?icons=${names.join(',')}`);
if (!res.ok) throw new Error(`Iconify API: ${res.status} ${res.statusText}`);
const data = await res.json();
if (data.not_found?.length) throw new Error(`Solar icons not found: ${data.not_found.join(', ')}`);

const icons = {};
for (const [slot, name] of Object.entries(SOLAR)) {
  icons[slot] = data.icons[`${name}-linear`].body.replaceAll('stroke-width="1.5"', 'stroke-width="1"');
}
Object.assign(icons, CUSTOM);

const out = `// Generated by scripts/build-annotator-icons.mjs: do not edit by hand.
// Solar linear icons (480 Design, CC BY 4.0) at a 1px stroke, 24x24 viewBox.
export const ANNOTATOR_ICONS = ${JSON.stringify(icons, null, 2)};
`;
writeFileSync(new URL('../src/annotator-icons.js', import.meta.url), out);
console.log(`annotator-icons.js: ${Object.keys(icons).length} icons`);
